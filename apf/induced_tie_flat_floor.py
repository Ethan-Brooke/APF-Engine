def _fractional_cell():
    """The diamond's single fractional cell, computed at the single
    AUTHORED magnitude through the banked callables.  Admissibility is
    decided ONCE PER SWITCHING CLASS: the constancy of the verdict inside
    a switching class is EE5(d)'s banked content, cited and consumed, and
    no per-member trial is run here."""
    if "cell" in _MEMO:
        return _MEMO["cell"]
    from apf import continuation_join_network as _cjn
    from apf import carrier_elliptope as _ce
    from apf import nonlocal_tie_resolution as _ntr
    verts = list(range(N_VERTS))
    edges = _cjn._sep_edges([list(b) for b in SEP_PARTITION], N_VERTS)
    cycles = _cjn._fundamental_cycles(verts, edges)
    pats, idx, classes = _cjn._switching_classes(edges, verts)
    eps = _ntr.EPS
    t = FRACTIONAL_MAGNITUDE
    rows = []
    for cl in classes:
        rep = cl[0]                       # once per class; see EE5(d)
        off = {e: eps * t * F(rep[idx[e]]) for e in edges}
        verdict = _ce.psd_by_minors(_ce.sym_from_offdiag(N_VERTS, eps, off))
        rows.append({"character": _cjn.holonomy_character(rep, idx, cycles),
                     "size": len(cl), "admissible": bool(verdict)})
    pool = [r for r in rows if r["character"][0] == 1]
    m = (F(sum(1 for r in pool if r["admissible"]), len(pool))
         if pool else None)
    _MEMO["cell"] = {"edges": frozenset(tuple(sorted(e)) for e in edges),
                     "cycles": cycles, "rows": rows, "pool_size": len(pool),
                     "m": m, "eps": eps, "magnitude": t}
    return _MEMO["cell"]


