def _token_hit(name, token):
    """Identifier-aware containment: the token occurs and is not glued to
    a LETTER on either side.  A bare substring scan reports names that
    merely contain the token inside a longer word, which is a known
    drift-net defect; underscores and digits stay boundaries so real
    identifier segments are still found."""
    low, tok, i = name.lower(), token.lower(), 0
    while True:
        i = low.find(tok, i)
        if i < 0:
            return False
        before = low[i - 1] if i > 0 else ""
        after = low[i + len(tok)] if i + len(tok) < len(low) else ""
        if not before.isalpha() and not after.isalpha():
            return True
        i += 1


def _resolve(module_path, attr):
    import importlib
    return getattr(importlib.import_module(module_path), attr)


def _invoke(fn, mode, subject, uniform, eps):
    if mode == "subject_only":
        return fn(subject)
    if mode == "subject_plus_diagonal":
        return fn(subject, tuple(eps for _ in subject))
    if mode == "subject_plus_arity":
        return fn(subject, len(subject))
    if mode == "subject_plus_reference":
        return fn(subject, tuple(uniform))
    raise KeyError(mode)


def _census_row(name, fn, mode, declared_kind, subjects, uniform, eps):
    """Execute one surface over the induced statistics and classify it.

    A surface acquires a NON-EMPTY REFUSAL EXTENSION only when it applies
    to the input at all, returns a verdict (a bool), and refuses some of
    the classes while admitting others.  A constant verdict on
    out-of-domain input decides no choice and is an alien-input artifact,
    not a refusal; a functional returning an exact value produces no
    refusal verdict at all, which is computed here from the returned
    type rather than judged."""
    outs, raised = [], None
    for sig, stat in subjects:
        try:
            outs.append((sig, _invoke(fn, mode, stat, uniform, eps)))
        except Exception as exc:              # the type boundary, executed
            raised = type(exc).__name__ + ": " + str(exc)[:70]
            break
    if raised is not None:
        return {"surface": name, "status": "TYPE_BOUNDARY",
                "declared_kind": declared_kind, "observed_kind": None,
                "exception": raised, "refusal_extension": False}
    kinds = {("verdict" if isinstance(v, bool) else
              ("value" if isinstance(v, (F, int)) else "other"))
             for _, v in outs}
    observed = kinds.pop() if len(kinds) == 1 else "mixed"
    values = {str(v) for _, v in outs}
    if observed == "verdict":
        refusing = sorted(s for s, v in outs if v is False)
        admitting = sorted(s for s, v in outs if v is True)
        if refusing and admitting:
            return {"surface": name, "status": "VERDICT_DISCRIMINATING",
                    "declared_kind": declared_kind,
                    "observed_kind": observed, "refusing": refusing,
                    "admitting": admitting, "refusal_extension": True}
        return {"surface": name,
                "status": "VERDICT_CONSTANT_DECIDES_NOTHING",
                "declared_kind": declared_kind, "observed_kind": observed,
                "constant_value": sorted(values),
                "note": "a constant verdict on out-of-domain input is an "
                        "alien-input artifact, not a refusal",
                "refusal_extension": False}
    return {"surface": name, "status": "VALUE_NO_VERDICT_PRODUCED",
            "declared_kind": declared_kind, "observed_kind": observed,
            "distinct_values": len(values), "refusal_extension": False}


