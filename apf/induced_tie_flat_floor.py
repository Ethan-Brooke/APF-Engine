def _flat_floor_removal(tables, m_point, reference, premise, floor_rec):
    """Returns the triple (status, the excluded set, the standing set).

    Granted the two readings and the identification premise, the whole
    mechanism -- this rule AND the reference law the caller passes in --
    is the banked floor's STATEMENT transcribed here, disclosed and not
    defended: born_at_ties' lemma is not a statistic-typed module-level
    callable and its record carries no law value, so no executable tie to
    the floor's statement is available.  What IS tied to the bank is the
    gate on the first line below, which reads the floor's own live record
    and refuses on any of four fields."""
    everything = tuple(sorted(tables))
    if not _floor_gate_met(floor_rec):
        return ("FLOOR_GATE_NOT_MET", (), everything)
    if premise is None:
        return ("PREMISE_WITHDRAWN_NO_DISCRIMINATION", (), everything)
