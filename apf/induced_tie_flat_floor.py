    if not premise.get("job_b_class_read_inside_counted_structure"):
        return ("REGISTER_FOLLOWER_GUARD_OUT_OF_UNIQUENESS_SCOPE",
                (), everything)
    removed = tuple(sorted(s for s, t in tables.items()
                           if t[m_point] != tuple(reference)))
    standing = tuple(sorted(set(tables) - set(removed)))
    return ("REMOVAL_UNDER_GRANTED_READINGS_AND_NAMED_PREMISE",
            removed, standing)


