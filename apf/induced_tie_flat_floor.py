def _numeric_leaves(obj, path=""):
    """Every numeric leaf of a returned record, with its path.  Used to
    execute -- not assert -- the claim that the banked floor's record
    carries no law VALUE this module could have consumed."""
    if isinstance(obj, dict):
        for k, v in sorted(obj.items(), key=lambda kv: str(kv[0])):
            for r in _numeric_leaves(v, path + "." + str(k)):
                yield r
    elif isinstance(obj, (list, tuple)):
        for i, v in enumerate(obj):
            for r in _numeric_leaves(v, path + "[%d]" % i):
                yield r
    elif isinstance(obj, (int, F)) and not isinstance(obj, bool):
        yield (path, obj)


