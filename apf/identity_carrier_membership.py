def _result(name, epistemic, key_result, evidence, fails, tier,
            dependencies, premises, negative_controls, cross_refs,
            leg_count, expected_legs):
    """Build the result dict and cross-assert THREE independently maintained
    records: the failure list, an independent failure counter, and the number
    of legs actually EXECUTED against a frozen contract.

    The executed-leg count exists because `ck` is a single funnel shared by
    every leg of every check here, so replacing it with a no-op would silence
    hundreds of assertions in one line while both failure records stayed
    consistent at zero.  A neutered funnel reports zero executed legs and is
    caught.  The contract is set-exact by design: adding or removing a leg is
    MEANT to break it.

    RESIDUAL LIMIT, DISCLOSED AND VERIFIED TO BE REAL: an edit that clears all
    three records together, or that substitutes the returned 'passed' literal,
    is NOT caught.  This was demonstrated against this module, not assumed.
    No module can defend against an edit to its own return statement."""
    counted = leg_count[0]
    executed = leg_count[1]
    if len(fails) != counted:
        raise AssertionError(
            f"{name}: failure records disagree -- fail_reasons has "
            f"{len(fails)} entries, the independent counter says {counted}")
    if executed != expected_legs:
        raise AssertionError(
            f"{name}: executed-leg count {executed} does not match the frozen "
            f"contract {expected_legs} -- either a leg was added or removed "
            f"without updating the contract, or the assertion funnel was "
            f"disabled")
    return {
        'fail_count': counted,
        'name': name,
        'epistemic': epistemic,
        'passed': (counted == 0),
        'tier': tier,
        'key_result': key_result,
        'evidence': evidence,
        'fail_reasons': fails,
        'dependencies': list(dependencies),
        'premises': list(premises),
        'negative_controls': list(negative_controls),
        'cross_refs': list(cross_refs),
        'physical_premises_certified': PHYSICAL_PREMISES_CERTIFIED,
        'exports': list(EXPORTS),
        'bank_modified': BANK_MODIFIED,
    }


def _ckr(fails: List[str], counter: List[int]):
    """counter[0] counts FAILURES; counter[1] counts INVOCATIONS."""
    def ck(cond: bool, msg: str) -> None:
        counter[1] += 1
        if not cond:
            fails.append(msg)
            counter[0] += 1
    return ck


