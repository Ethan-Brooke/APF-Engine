Q = Tuple[F, F]
Mat = List[List[Q]]

_Z: Q = (F(0), F(0))
_ONE: Q = (F(1), F(0))
_I: Q = (F(0), F(1))


def _q(a, b=0) -> Q:
    return (F(a), F(b))


def _add(x: Q, y: Q) -> Q:
    return (x[0] + y[0], x[1] + y[1])


def _sub(x: Q, y: Q) -> Q:
    return (x[0] - y[0], x[1] - y[1])


def _mul(x: Q, y: Q) -> Q:
    return (x[0] * y[0] - x[1] * y[1], x[0] * y[1] + x[1] * y[0])


def _conj(x: Q) -> Q:
    return (x[0], -x[1])


def _neg(x: Q) -> Q:
    return (-x[0], -x[1])


def _isz(x: Q) -> bool:
    return x[0] == 0 and x[1] == 0


def _zeros(n: int, m: int = None) -> Mat:
    m = n if m is None else m
    return [[_Z for _ in range(m)] for _ in range(n)]


def _eye(n: int) -> Mat:
    a = _zeros(n)
    for i in range(n):
        a[i][i] = _ONE
    return a


def _unit(i: int, j: int, n: int) -> Mat:
    a = _zeros(n)
    a[i][j] = _ONE
    return a


def _mm(a: Mat, b: Mat) -> Mat:
    n, k, m = len(a), len(b), len(b[0])
    c = _zeros(n, m)
    for i in range(n):
        for j in range(m):
            s = _Z
            for t in range(k):
                s = _add(s, _mul(a[i][t], b[t][j]))
            c[i][j] = s
    return c


def _mv(a: Mat, v: Sequence[Q]) -> List[Q]:
    out = []
    for i in range(len(a)):
        s = _Z
        for j in range(len(v)):
            s = _add(s, _mul(a[i][j], v[j]))
        out.append(s)
    return out


def _dag(a: Mat) -> Mat:
    return [[_conj(a[j][i]) for j in range(len(a))] for i in range(len(a[0]))]


def _conjm(a: Mat) -> Mat:
    return [[_conj(x) for x in r] for r in a]


def _scal(s: Q, a: Mat) -> Mat:
    return [[_mul(s, x) for x in r] for r in a]


def _addm(a: Mat, b: Mat) -> Mat:
    return [[_add(a[i][j], b[i][j]) for j in range(len(a[0]))]
            for i in range(len(a))]


def _subm(a: Mat, b: Mat) -> Mat:
    return [[_sub(a[i][j], b[i][j]) for j in range(len(a[0]))]
            for i in range(len(a))]


def _eqm(a: Mat, b: Mat) -> bool:
    if len(a) != len(b) or len(a[0]) != len(b[0]):
        return False
    return all(a[i][j] == b[i][j]
               for i in range(len(a)) for j in range(len(a[0])))


def _comm(a: Mat, b: Mat) -> Mat:
    return _subm(_mm(a, b), _mm(b, a))


def _iszm(a: Mat) -> bool:
    return all(_isz(a[i][j]) for i in range(len(a)) for j in range(len(a[0])))


def _kron(a: Mat, b: Mat) -> Mat:
    n, m = len(a), len(b)
    c = _zeros(n * m)
    for i in range(n):
        for j in range(n):
            for k in range(m):
                for l in range(m):
                    c[i * m + k][j * m + l] = _mul(a[i][j], b[k][l])
    return c


def _trace(a: Mat) -> Q:
    s = _Z
    for i in range(len(a)):
        s = _add(s, a[i][i])
    return s


def _is_hermitian(a: Mat) -> bool:
    return _eqm(a, _dag(a))


def _flat(a: Mat) -> List[Q]:
    return [a[i][j] for i in range(len(a)) for j in range(len(a[0]))]


def _rank(rows: Sequence[Sequence[Q]]) -> int:
    m = [list(r) for r in rows]
    if not m:
        return 0
    cols = len(m[0])
    rank = 0
    for c in range(cols):
        piv = next((i for i in range(rank, len(m)) if not _isz(m[i][c])), None)
        if piv is None:
            continue
        m[rank], m[piv] = m[piv], m[rank]
        d = m[rank][c][0] ** 2 + m[rank][c][1] ** 2
        inv = (m[rank][c][0] / d, -m[rank][c][1] / d)
        m[rank] = [_mul(inv, x) for x in m[rank]]
        for i in range(len(m)):
            if i != rank and not _isz(m[i][c]):
                f = m[i][c]
                m[i] = [_sub(m[i][j], _mul(f, m[rank][j]))
                        for j in range(cols)]
        rank += 1
    return rank


def _charpoly(a: Mat) -> List[Q]:
    n = len(a)
    cur = [row[:] for row in a]
    cs: List[Q] = [_ONE]
    for k in range(1, n + 1):
        ck = _mul(_q(F(-1, k)), _trace(cur))
        cs.append(ck)
        if k < n:
            t = [row[:] for row in cur]
            for i in range(n):
                t[i][i] = _add(t[i][i], ck)
            cur = _mm(a, t)
    return cs


def _is_psd_hermitian(a: Mat) -> bool:
    """PSD for a HERMITIAN argument, by characteristic-polynomial signs.  The
    criterion is unsound off the Hermitian slice, so Hermiticity is enforced
    by raising rather than by returning False."""
    if not _is_hermitian(a):
        raise AssertionError(
            "_is_psd_hermitian called on a non-Hermitian matrix: the "
            "characteristic-polynomial sign criterion is unsound there")
    cs = _charpoly(a)
    for k in range(1, len(a) + 1):
        if cs[k][1] != 0:
            raise AssertionError(
                "Hermitian matrix produced a non-real charpoly coefficient")
        if ((-1) ** k) * cs[k][0] < 0:
            return False
    return True


def _partial_transpose(r: Mat, n: int) -> Mat:
    """Transpose the SECOND (reference) factor.  Used only in the corollary.

    DISCLOSED, TWO LEVELS.  (1) On every object this module feeds it the
    spectrum is invariant under transposing the first factor instead, so no
    leg distinguishes the two conventions here; the docstring is the record of
    which is intended.  (2) More generally, a GLOBAL relabelling of the two
    tensor legs -- swapping the argument order of _kron everywhere -- is a
    symmetry of this module's own language and is undetectable from inside it,
    since every construction and every assertion would swap together.  What IS
    detected is a LOCALLY wrong leg: the corollary pins its conditional
    expectation against an asymmetric witness on which the reference-leg and
    system-leg maps disagree completely."""
    p = _zeros(n * n)
    for i in range(n):
        for j in range(n):
            for k in range(n):
                for l in range(n):
                    p[i * n + k][j * n + l] = r[i * n + l][j * n + k]
    return p


def _omega_density(n: int) -> Mat:
    """rho_Omega = |Omega><Omega| / n, |Omega> = sum_i |i>|i>."""
    v = [_Z] * (n * n)
    for i in range(n):
        v[i * n + i] = _ONE
    r = [[_mul(v[i], _conj(v[j])) for j in range(n * n)] for i in range(n * n)]
    return _scal(_q(F(1, n)), r)


def _left_slices(t: Mat, n: int) -> List[Mat]:
    """Left support generators: the slices (id (x) phi_{kl})(T)."""
    out = []
    for k in range(n):
        for l in range(n):
            s = _zeros(n)
            for i in range(n):
                for j in range(n):
                    s[i][j] = t[i * n + k][j * n + l]
            out.append(s)
    return out


def _right_slices(t: Mat, n: int) -> List[Mat]:
    out = []
    for k in range(n):
        for l in range(n):
            s = _zeros(n)
            for i in range(n):
                for j in range(n):
                    s[i][j] = t[k * n + i][l * n + j]
            out.append(s)
    return out


