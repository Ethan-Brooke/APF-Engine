def register(registry):
    """Entry point the bank calls.  Keys are the check_ names, so registry key
    == fn.__name__ == result['name'] for every entry."""
    registry.update(_CHECKS)
    return registry


def run_all():
    """Second gate only; the load-bearing cross-assert lives in _result()."""
    out = {}
    for n, fn in _CHECKS.items():
        r = fn()
        listed = len(r['fail_reasons'])
        counted = r['fail_count']
        if listed != counted:
            raise AssertionError(
                f"{n}: failure records disagree -- fail_reasons has {listed} "
                f"entries, the independent counter says {counted}")
        if n != r['name'] or _CHECKS[n].__name__ != n:
            raise AssertionError(
                f"registry key {n!r} must match the function name and the "
                f"result name")
        r['passed'] = (counted == 0)
        out[n] = r
    return out


