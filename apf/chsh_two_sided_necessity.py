# relation-level algebra: polynomials over words (a-word, b-word)
#
# A monomial is a pair (wa, wb) of letter tuples.  Writing every monomial
# with its a-letters to the left of its b-letters uses a_i b_j = b_j a_i.
# A reducer applies x^2 = 1 (free reducer), or x^2 = 1 together with
# commutation of the two letters on that side (commuting reducer).  Every
# step is a consequence of the stated relations, so equality of reduced
# forms is equality in every realization.
# ---------------------------------------------------------------------------

def _reduce_free(word):
    out = []
    for x in word:
        if out and out[-1] == x:
            out.pop()
        else:
            out.append(x)
    return tuple(out)


def _reduce_commuting(word):
    return tuple(sorted(x for x in set(word) if word.count(x) % 2 == 1))


def _reducer_conformance(reducer, commuting):
    """Value checks that a reducer applies the relations it is named for.
    Returns the list of words on which it does not, and the number of
    words checked."""
    want = [((), ()), ((1,), (1,)), ((2,), (2,)), ((1, 1), ()),
            ((2, 2), ()), ((1, 2, 2, 1), ()), ((1, 2), (1, 2))]
    if commuting:
        want += [((2, 1), (1, 2)), ((1, 2, 1), (2,)), ((2, 1, 2, 1), ())]
    else:
        want += [((2, 1), (2, 1)), ((1, 2, 1), (1, 2, 1)),
                 ((2, 1, 2, 1), (2, 1, 2, 1))]
    return [w for w, r in want if reducer(w) != r], len(want)


def _pmul(p, q, ra, rb):
    out = {}
    for (wa, wb), c in p.items():
        for (va, vb), d in q.items():
            key = (ra(wa + va), rb(wb + vb))
            out[key] = out.get(key, 0) + c * d
    return {k: v for k, v in out.items() if v != 0}


def _padd(p, q, sign=1):
    out = dict(p)
    for k, v in q.items():
        out[k] = out.get(k, 0) + sign * v
    return {k: v for k, v in out.items() if v != 0}


def _pscal(s, p):
    return {k: s * v for k, v in p.items() if s * v != 0}


_ONE = {((), ()): 1}


def _a(i):
    return {((i,), ()): 1}


def _b(j):
    return {((), (j,)): 1}


def _sym_S(coeff, ra, rb):
    s = {}
    for (i, j), c in sorted(coeff.items()):
        s = _padd(s, _pscal(c, _pmul(_a(i), _b(j), ra, rb)))
    return s


def _sym_comm(x, y, ra, rb):
    return _padd(_pmul(x, y, ra, rb), _pmul(y, x, ra, rb), sign=-1)


def _sym_rhs(ra, rb, sign=-1, const=4):
    prod = _pmul(_sym_comm(_a(1), _a(2), ra, rb),
                 _sym_comm(_b(1), _b(2), ra, rb), ra, rb)
    return _padd(_pscal(const, _ONE), prod, sign=sign)


