def _eye(n):
    return [[F(1) if i == j else F(0) for j in range(n)] for i in range(n)]


def _mm(A, B):
    n, m, k = len(A), len(B[0]), len(B)
    return [[sum((A[i][t] * B[t][j] for t in range(k)), F(0))
             for j in range(m)] for i in range(n)]


def _lin(alpha, A, beta, B):
    return [[alpha * A[i][j] + beta * B[i][j] for j in range(len(A[0]))]
            for i in range(len(A))]


def _scal(s, A):
    return [[s * x for x in row] for row in A]


def _kron(A, B):
    na, nb = len(A), len(B)
    return [[A[i][j] * B[k][l] for j in range(na) for l in range(nb)]
            for i in range(na) for k in range(nb)]


def _is0(A):
    return all(x == 0 for row in A for x in row)


def _eq(A, B):
    return all(A[i][j] == B[i][j]
               for i in range(len(A)) for j in range(len(A[0])))


def _comm(A, B):
    return _lin(F(1), _mm(A, B), F(-1), _mm(B, A))


def _all_fraction(A):
    return all(isinstance(x, F) for row in A for x in row)


def _reflection(v):
    """I - 2 v v^T / (v.v): exact, symmetric, squares to the identity."""
    n = len(v)
    vv = sum(F(x) * F(x) for x in v)
    return [[(F(1) if i == j else F(0)) - 2 * F(v[i]) * F(v[j]) / vv
             for j in range(n)] for i in range(n)]


def _is_pm1_observable(A):
    n = len(A)
    sym = all(A[i][j] == A[j][i] for i in range(n) for j in range(n))
    return sym and _eq(_mm(A, A), _eye(n)) and _all_fraction(A)


def _S_matrix(a1, a2, b1, b2, coeff):
    obs_a = {1: a1, 2: a2}
    obs_b = {1: b1, 2: b2}
    n = len(a1) * len(b1)
    S = [[F(0)] * n for _ in range(n)]
    for (i, j), c in sorted(coeff.items()):
        S = _lin(F(1), S, F(c), _kron(obs_a[i], obs_b[j]))
    return S


def _expect_pure(v, M):
    """<v| M |v> / <v|v> for an integer vector v: the expectation in the
    rational pure state it spans."""
    n = len(v)
    num = sum((F(v[i]) * M[i][j] * F(v[j])
               for i in range(n) for j in range(n)), F(0))
    return num / sum(F(x) * F(x) for x in v)


