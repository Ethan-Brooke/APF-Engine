def _state_vectors(n):
    """Authored integer vectors spanning rational pure states in dimension
    n."""
    ones = [1] * n
    ramp = list(range(1, n + 1))
    alt = [1 if k % 2 == 0 else -1 for k in range(n)]
    ends = [1] + [0] * (n - 2) + [1]
    ends_minus = [1] + [0] * (n - 2) + [-1]
    first = [1] + [0] * (n - 1)
    skew = [((k * k + 1) % 5) - 2 for k in range(n)]
    out = []
    for v in (ones, ramp, alt, ends, ends_minus, first, skew):
        if any(x != 0 for x in v) and v not in out:
            out.append(v)
    return out


def _sign_patterns():
    """The eight CHSH facet sign patterns, generated here independently of
    the bridge engine: all sign 4-tuples whose product is -1."""
    return [s for s in _iproduct((1, -1), repeat=4)
            if s[0] * s[1] * s[2] * s[3] == -1]


def _correlator_table(v, a1, a2, b1, b2):
    return (_expect_pure(v, _kron(a1, b1)), _expect_pure(v, _kron(a1, b2)),
            _expect_pure(v, _kron(a2, b1)), _expect_pure(v, _kron(a2, b2)))


def _facet_values(E):
    return [sum((F(s[k]) * E[k] for k in range(4)), F(0))
            for s in _sign_patterns()]


def _facets_above_two(instances):
    """Facet expectations over the given instances and the authored states:
    how many were evaluated, and those above 2 in absolute value."""
    evaluated, above = 0, []
    for da, db, la, lb, a1, a2, b1, b2 in instances:
        for v in _state_vectors(da * db):
            for val in _facet_values(_correlator_table(v, a1, a2, b1, b2)):
                evaluated += 1
                if abs(val) > 2:
                    above.append((da, db, la, lb, tuple(v), str(val)))
    return evaluated, above


