def _tv(p, q):
    """The record total-variation distance, by definition, exact."""
    return sum(abs(x - y) for x, y in zip(p, q)) / 2


def _dw(a_u, a_v, p, q):
    """The prior-inclusive variant (NOT a permitted definition; computed
    only to break it in SR3/NC4 and to exhibit its equal-prior reduction)."""
    return sum(abs(a_u * x - a_v * y) for x, y in zip(p, q))


def _guess(a_u, a_v, p, q):
    """The Bayes guessing probability, by its own max-sum route (the
    independent second route of the SR3 identity legs; anchored by value
    to the enumerated Bayes optimum in the SR3 anchor leg)."""
    return sum(max(a_u * x, a_v * y) for x, y in zip(p, q))


def _bayes_enum(a_u, a_v, p, q):
    """The Bayes optimum by enumeration: every deterministic guessing rule
    (each cell answered u or v; 2^|cells| rules) is evaluated as its
    prior-weighted success probability, and the maximum over the full
    rule list is returned together with the rule count and the value
    list."""
    m = len(p)
    vals = []
    for rule in range(2 ** m):
        vals.append(sum((a_u * p[k]) if (rule >> k) & 1 else (a_v * q[k])
                        for k in range(m)))
    best = vals[0]
    for v in vals[1:]:
        if v > best:
            best = v
    return best, len(vals), vals


