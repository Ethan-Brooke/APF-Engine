    # (i) INDEPENDENT -- the recovery is the same `_riesz_recover` call, on a
    #     spanning family, that `riesz_round_trip_by_value` grades "costs
    #     nothing";
    # (ii) AN IDENTITY, NOT A SECOND MEASUREMENT -- `_rank_added` is
    #      ranks[3] - ranks[1] and `_one_basis_nullity` is len(B) - ranks[1],
    #      and ranks[3] == len(B) == 6 is asserted in the leg above, so the
    #      two expressions are the same number by arithmetic.  Their
    #      agreement measures nothing; the content is the value 3;
    # (iii) A RESTATEMENT -- exact recovery of 7 distinct operators from
    #       these values already entails 7 distinct value-tuples, so the
