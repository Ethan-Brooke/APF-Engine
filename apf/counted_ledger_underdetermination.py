# ===================================================== exact rational algebra
def _mm(A, B):
    k = len(B)
    return [[sum(A[i][t] * B[t][j] for t in range(k)) for j in range(len(B[0]))]
            for i in range(len(A))]


def _tp(A):
    return [[A[j][i] for j in range(len(A))] for i in range(len(A[0]))]


def _tr(A):
    return sum(A[i][i] for i in range(len(A)))


def _det(M):
    m = len(M)
    if m == 1:
        return M[0][0]
    acc = F(0)
    for j in range(m):
        minor = [[M[i][k] for k in range(m) if k != j] for i in range(1, m)]
        t = M[0][j] * _det(minor)
        acc += t if j % 2 == 0 else -t
    return acc


def _psd(M):
    """Sylvester over ALL principal minors -- valid for the PSD (non-strict)
    cone, where the leading-minor test alone is not."""
    n = len(M)
    for s in range(1, n + 1):
        for idx in combinations(range(n), s):
            if _det([[M[i][j] for j in idx] for i in idx]) < 0:
                return False
    return True


def _rank(rows):
    M = [r[:] for r in rows]
    if not M:
        return 0
    dim = len(M[0])
    r = 0
    for c in range(dim):
        p = next((k for k in range(r, len(M)) if M[k][c] != 0), None)
        if p is None:
            continue
        M[r], M[p] = M[p], M[r]
        pv = M[r][c]
        M[r] = [x / pv for x in M[r]]
        for k in range(len(M)):
            if k != r and M[k][c] != 0:
                f = M[k][c]
                M[k] = [x - f * y for x, y in zip(M[k], M[r])]
        r += 1
        if r == len(M):
            break
    return r


# ------------------------------------------------- complex rationals over Q(i)
class CQ:
    __slots__ = ("re", "im")

    def __init__(self, re, im=F(0)):
        self.re, self.im = F(re), F(im)

    def __add__(self, o):
        return CQ(self.re + o.re, self.im + o.im)

    def __mul__(self, o):
        return CQ(self.re * o.re - self.im * o.im,
                  self.re * o.im + self.im * o.re)

    def conj(self):
        return CQ(self.re, -self.im)

    def __eq__(self, o):
        return isinstance(o, CQ) and self.re == o.re and self.im == o.im

    def __hash__(self):
        return hash((self.re, self.im))

    def __repr__(self):
        sign = "+" if self.im >= 0 else "-"
        return "%s %s %si" % (self.re, sign, abs(self.im))


