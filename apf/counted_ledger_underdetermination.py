def _conjugated_resolution(U, E):
    return [_mm(_mm([list(r) for r in U], Ek), _tp([list(r) for r in U]))
            for Ek in E]


def _read_rows(Us, E, B):
    """The linear map X |-> (Tr(X F)) for every effect F of every resolution,
    in coordinates on the basis B."""
    rows = []
    for U in Us:
        for Ek in _conjugated_resolution(U, E):
            rows.append([_hs(Ek, P) for P in B])
    return rows


def _riesz_recover(vals, gram, basis, n):
    """Recover the unique symmetric operator whose Hilbert-Schmidt pairings
    with `basis` are `vals`.  Exact Gauss-Jordan over Q."""
    d = len(basis)
    aug = [gram[i][:] + [vals[i]] for i in range(d)]
    for c in range(d):
        p = next(k for k in range(c, d) if aug[k][c] != 0)
        aug[c], aug[p] = aug[p], aug[c]
        pv = aug[c][c]
        aug[c] = [t / pv for t in aug[c]]
        for k in range(d):
            if k != c and aug[k][c] != 0:
                f = aug[k][c]
                aug[k] = [t - f * u for t, u in zip(aug[k], aug[c])]
    coeff = [aug[i][d] for i in range(d)]
    X = [[F(0)] * n for _ in range(n)]
    for cf, P in zip(coeff, basis):
        for i in range(n):
            for j in range(n):
                X[i][j] += cf * P[i][j]
    return X


