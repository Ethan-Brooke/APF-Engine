def _factors_through(values, classes):
    """values and classes are dicts on the same keys.  Returns True iff the
    assignment key |-> values[key] is constant on every class of
    key |-> classes[key], i.e. iff `values` factors through `classes`."""
    buckets: Dict[object, set] = {}
    for k, cl in classes.items():
        buckets.setdefault(cl, set()).add(values[k])
    return all(len(v) == 1 for v in buckets.values())


def _cq_off(rho):
    return ((rho[0][1].re, rho[0][1].im), (rho[0][2].re, rho[0][2].im),
            (rho[1][2].re, rho[1][2].im))


