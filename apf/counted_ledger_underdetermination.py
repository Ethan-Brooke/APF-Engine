def _projectors(n):
    out = []
    for k in range(n):
        P = [[F(0)] * n for _ in range(n)]
        P[k][k] = F(1)
        out.append(P)
    return out


def _sym_basis(n):
    """Basis of Sym(n): the n diagonal units and the n(n-1)/2 symmetric pairs."""
    B = []
    for i in range(n):
        M = [[F(0)] * n for _ in range(n)]
        M[i][i] = F(1)
        B.append(M)
    for i in range(n):
        for j in range(i + 1, n):
            M = [[F(0)] * n for _ in range(n)]
            M[i][j] = F(1)
            M[j][i] = F(1)
            B.append(M)
    return B


def _hs(A, B):
    n = len(A)
    return sum(A[i][j] * B[i][j] for i in range(n) for j in range(n))


def _rho_from_carrier(b):
    """rho_b = b b* / Tr(b b*) -- the representation-side object,
    presentation_gauge_forcing.py:59-62.  Real entries."""
    bb = _mm(b, _tp(b))
    t = _tr(bb)
    return [[x / t for x in row] for row in bb]


def _rho_from_carrier_cq(v):
    """rho_b for a COLUMN carrier over Q(i): rho_ij = v_i conj(v_j) / |v|^2."""
    n = len(v)
    nrm = sum((v[k] * v[k].conj()).re for k in range(n))
    return [[CQ((v[i] * v[j].conj()).re / nrm, (v[i] * v[j].conj()).im / nrm)
             for j in range(n)] for i in range(n)]


