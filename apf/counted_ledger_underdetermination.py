                 "a conjunct here, so a loop over fewer of them is "
                 "reported. The fiber has NINE members; what these three "
                 "REAL resolutions return on the other two is computed in "
                 "`three_real_resolutions_return_only_the_real_part`. "
                 "The %d at TWO resolutions is a property of U2_ROT and not "
                 "of the number two: U2_ROT is block-diagonal and fixes E_2, "
                 "and the same read with the non-block-diagonal U3_ROT is "
