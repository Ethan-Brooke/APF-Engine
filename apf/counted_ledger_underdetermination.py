        "on every E_k and %d distinct values on a single off-diagonal "
        "effect. Riesz names the EFFECT slot: it returns an operator for an "
        "affine functional that is not positive, so it is not delivering "
        "b b* / Tr(b b*) for any carrier. THE NULLITY IS ALSO REACHED BY "
