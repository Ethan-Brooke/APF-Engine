def _parse_extensive_partition(summary):
    """Parse the extensive partition figures from the banked transfer
    record's own returned summary (values from the banked return, never a
    literal).  Returns (total, parts) as ints or None."""
    m = re.search(r"C_total = (\d+) = (\d+) \+ (\d+) \+ (\d+)", summary)
    if not m:
        return None
    total = int(m.group(1))
    parts = (int(m.group(2)), int(m.group(3)), int(m.group(4)))
    return total, parts


def _parse_transfer_instance(summary):
    """Parse the transfer-instance retained fraction from the banked
    return.  Returns a Fraction or None."""
