def _step_ingredients_hold(n, q):
    """The permanence step's two exact ingredients at n for ratio q:
    (a) the cross-multiplied integer identity
        (n+1)*(n*q+1) - n*((n+1)*q+1) == 1  (computed, not assumed), and
    (b) the square comparison (n+1)^2 <= 2*n^2 (n >= 3 on every call
    path).  Together they chain the schedule's squared bound at n into
    the doubled bound at n+1."""
