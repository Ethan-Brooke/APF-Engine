def cycle_edges(n):
    """The n-cycle's edge list in cycle order, normalized (i < j).
    Edge index i carries the sign of the i-th cycle edge."""
    return [(min(i, (i + 1) % n), max(i, (i + 1) % n))
            for i in range(n)]


def grid_for(tie_n, strata):
    """The evaluation grid of a NAMED physical scope: (tie_index, n,
    magnitude, parity).  The frozen scope's grid is
    grid_for(TIE_N, STRATA); FPF3's robustness leg names its extended
    physical grids as AUTHORED probes and computes them through this
    same constructor."""
    pts = []
    for ti, n in enumerate(tie_n):
        for mag in strata[n]:
            for parity in PARITIES:
                pts.append((ti, n, mag, parity))
    return tuple(pts)


