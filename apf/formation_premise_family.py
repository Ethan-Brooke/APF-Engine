def measure_m(n, parity, magnitude):
    """THE NORMALIZED CLASS MEASURE -- this module's own object.

    m = (number of members of the cycle-parity class whose carrier
    passes the banked carrier_elliptope.psd_by_minors) / (size of the
    class).  Exact Fraction.

    DISCLOSED, IDENTITY-GRADE (the class_admissibility_windows
    leg-(b) genre): the per-member execution below cannot return
    differing verdicts inside one class -- membership is invariant
    under diagonal sign conjugation (extended_carrier_elliptope
    EE5(d), CONSUMED, never re-proved and never sampled here) and the
    parity class IS one switching class at h = 1
    (continuation_join_network J2/J3, CONSUMED).  The per-member loop
    certifies that the route EXECUTED across the whole class; the
    constancy is the bank's, not this module's.  A count-free route
    to the same value is computed independently in FPF4 and
    value-tied to this one.

    THE QUOTIENT IS UNEXERCISED HERE and is pinned elsewhere: at h = 1
    the numerator is 0 or the full class size, so this route forms only
    0/k and k/k.  FPF4's permanent control exercises
    `normalized_class_measure` and `admissible_count` OFF this grid and
    pins that `measure_m` routes through both; E4 states the control's
    reach and its limit.
    """
    key = (n, parity, magnitude)
    if key in _MEASURE_CACHE:
        return _MEASURE_CACHE[key]
    members = parity_class(n, parity)
    adm = admissible_count(members, n, magnitude)
    m = normalized_class_measure(adm, len(members))
    _MEASURE_CACHE[key] = m
    return m


