def parity_class(n, parity):
    """The cycle-parity class: every sign assignment on the n-cycle
    whose cycle product -- computed through the banked
    global_defect_margin._cycle_product -- equals `parity`."""
    return frozenset(tuple(s) for s in product((1, -1), repeat=n)
                     if _gdm._cycle_product(tuple(s)) == parity)


def carrier_of(n, signs, magnitude):
    """The carrier matrix of one sign assignment, built through
    carrier_elliptope's own constructor at the EPS diagonal."""
    off = {}
    for i in range(n):
        a, b = i, (i + 1) % n
        off[(min(a, b), max(a, b))] = signs[i] * magnitude * EPS
    return _ce.sym_from_offdiag(n, EPS, off)


