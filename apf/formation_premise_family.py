def separates_at_cell(imap, cell):
    """Non-constancy across the two composition classes at one
    executed stratum."""
    ti, n, mag = cell
    return imap[(ti, n, mag, 1)] != imap[(ti, n, mag, -1)]


def tie_profile(cand):
    """The per-tie outcome profile: COMPLETES at a tie iff the induced
    map is non-constant across the classes at some stratum of that
    tie; COMPOSITION_INDEPENDENT otherwise."""
    imap = induced_map(cand)
    out = []
    for ti, n in enumerate(TIE_N):
        sep = any(separates_at_cell(imap, (ti, n, mag))
                  for mag in STRATA[n])
        out.append("COMPLETES" if sep else "COMPOSITION_INDEPENDENT")
    return tuple(out)


def completes(cand):
    """The completion predicate, route 1: non-constancy across class
    at at least one executed separating stratum."""
    return "COMPLETES" in tie_profile(cand)


def nonconstant_across_class(cand):
    """The completion predicate, route 2, computed independently of
    route 1: the induced map restricted to a class is compared class
    against class over the stratum cells."""
    imap = induced_map(cand)
    by_class = {p: tuple(imap[(ti, n, mag, p)]
                         for (ti, n, mag) in STRATUM_CELLS)
                for p in PARITIES}
    return by_class[1] != by_class[-1]


def ordinal_signature_over(cand, grid):
    """The favored-arm pattern on a grid: per grid point, 'A' (the
    first arm of the table pair), 'B' (the second) or 'T' (tied)."""
    imap = induced_map_over(cand, grid)
    pat = []
    for g in grid:
        a, b = imap[g]
        pat.append("A" if a > b else ("B" if b > a else "T"))
    return tuple(pat)


def ordinal_signature(cand):
    """The favored-arm pattern on the executed grid."""
    return ordinal_signature_over(cand, GRID)


def completes_over(cand, grid):
    """The completion predicate on a grid: non-constancy across the
    two composition classes at some stratum cell of that grid."""
    imap = induced_map_over(cand, grid)
    cells = sorted({(ti, n, mag) for (ti, n, mag, _p) in grid})
    return any(imap[(ti, n, mag, 1)] != imap[(ti, n, mag, -1)]
               for (ti, n, mag) in cells)


