def admissible_count(members, n, magnitude):
    """THE NUMERATOR, isolated as a named callable so a control can
    exercise it on an authored set whose members' banked PSD verdicts
    DIFFER -- which no single cycle-parity class does at h = 1.  Counts
    the members whose carrier passes carrier_elliptope.psd_by_minors."""
    _ADMISSIBLE_COUNT_CALLS[0] += 1
    return sum(1 for s in members
               if _ce.psd_by_minors(carrier_of(n, s, magnitude)))


