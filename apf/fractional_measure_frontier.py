    expected_cells = len(inventory) * 2 * len(EXECUTED_STRATA)
    # non-vacuity: both sides of the biconditional are realized, and the
    # coarsening clause alone is realized without the fraction
    coarsens_but_not_fractional = [c for c in cells
                                   if c["strictly_coarsens"]
                                   and not c["fractional"]]
    # the two clauses are NOT independent, and the module says so rather
    # than letting the entailment sit hidden inside the conjunction
    differ_without_coarsening = [c for c in cells
                                 if c["verdicts_differ"]
                                 and not c["strictly_coarsens"]]
    reads_nonconstant = all(
        len({_measured_class_chars(configs[name], p) for p in (1, -1)}) == 2
        for name, _p, _n in inventory)
    criterion_ok = (biconditional_ok
                    and len(cells) == expected_cells
                    and len(cells) == 18
                    and len(fractional_cells) == 1
                    and len(coarsens_but_not_fractional) == 5
                    and len(differ_without_coarsening) == 0
                    and reads_nonconstant)
