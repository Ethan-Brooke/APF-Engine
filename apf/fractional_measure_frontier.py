    configs = {name: _configuration(part, cn)
               for name, part, cn in inventory}

    # -- the criterion, cell by cell ------------------------------------
    cells = []
    biconditional_ok = True
    for name, _part, _cn in inventory:
        cfg = configs[name]
        for parity in (1, -1):
            pooled = _measured_class_chars(cfg, parity)
            for mag in EXECUTED_STRATA:
                verdicts = tuple(_class_admissible(cfg, ch, mag)
                                 for ch in pooled)
                m = F(sum(1 for v in verdicts if v), len(verdicts))
                coarsens = len(pooled) > 1
                differ = len(set(verdicts)) > 1
                fractional = m not in (F(0), F(1))
                if fractional != (coarsens and differ):
                    biconditional_ok = False
                cells.append({
                    "configuration": name,
                    "cyclomatic_dimension": cfg["h"],
                    "parity": parity,
                    "magnitude": str(mag),
                    "classes_pooled": len(pooled),
                    "strictly_coarsens": coarsens,
                    "verdicts_differ": differ,
                    "measure": str(m),
                    "fractional": fractional})
