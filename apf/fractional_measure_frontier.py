class _Quad:
    """An element a + b*sqrt(D) of a real quadratic ring, with exact
    rational a and b.  Used ONLY to verify that a named root annihilates
    its quadratic exactly and lies strictly inside a rational bracket;
    its arithmetic is exact rational throughout."""

    __slots__ = ("a", "b", "d")

    def __init__(self, a, b, d):
        self.a, self.b, self.d = F(a), F(b), int(d)

    def __add__(self, o):
        return _Quad(self.a + o.a, self.b + o.b, self.d)

    def __sub__(self, o):
        return _Quad(self.a - o.a, self.b - o.b, self.d)

    def __mul__(self, o):
        return _Quad(self.a * o.a + self.d * self.b * o.b,
                     self.a * o.b + self.b * o.a, self.d)

    def scaled(self, k):
        return _Quad(self.a * F(k), self.b * F(k), self.d)

    def is_zero(self):
        return self.a == 0 and self.b == 0

    def eq_rational(self, r):
        """Exact equality a + b*sqrt(D) == r, for b >= 0 and D > 0."""
        if self.b < 0:
            raise ValueError("comparison implemented for b >= 0 only")
        if self.b == 0:
            return self.a == F(r)
        diff = F(r) - self.a
        return diff >= 0 and diff * diff == self.d * self.b * self.b

    def gt_rational(self, r):
        """Exact comparison a + b*sqrt(D) > r, for b >= 0 and D > 0."""
        diff = self.a - F(r)
        if self.b < 0:
            raise ValueError("comparison implemented for b >= 0 only")
        if diff >= 0:
            return not (diff == 0 and self.b == 0)
        return self.d * self.b * self.b > diff * diff

    def __repr__(self):
        return f"{self.a} + {self.b}*sqrt({self.d})"


def _binom(n, k):
    """Exact integer binomial coefficient, by integer arithmetic only --
    an enumeration-independent route to the census population."""
    if k < 0 or k > n:
        return 0
    num, den = 1, 1
    for i in range(k):
        num *= (n - i)
        den *= (i + 1)
    return num // den


def _poly_mul(a, b):
    out = [F(0)] * (len(a) + len(b) - 1)
    for i, x in enumerate(a):
        for j, y in enumerate(b):
            out[i + j] += x * y
    return out


def _poly_trim(c):
    c = list(c)
    while len(c) > 1 and c[-1] == 0:
        c.pop()
    return c


def _poly_eval(c, t):
    v = F(0)
    for coeff in reversed(c):
        v = v * t + coeff
    return v


def _interpolate(points):
    """Exact Lagrange interpolation from (x, y) pairs to an ascending
    coefficient list.  Fractions throughout."""
    xs = [p[0] for p in points]
    ys = [p[1] for p in points]
    coeffs = [F(0)] * len(xs)
    for i, xi in enumerate(xs):
        basis = [F(1)]
        den = F(1)
        for j, xj in enumerate(xs):
            if i == j:
                continue
            nxt = [F(0)] * (len(basis) + 1)
            for k, cf in enumerate(basis):
                nxt[k] += cf * (-xj)
                nxt[k + 1] += cf
            basis = nxt
            den *= (xi - xj)
        for k, cf in enumerate(basis):
            coeffs[k] += ys[i] * cf / den
    return _poly_trim(coeffs)


